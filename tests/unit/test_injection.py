from __future__ import annotations

from pathlib import Path

import pytest

from csauto.qoi import Recipe
from csauto.qoi.errors import QoIError
from csauto.qoi.injection import (
    InjectionReport,
    inject_user_files_into_case,
    inject_user_files_into_runs,
)


def _force_recipe(name: str = "Cd", boundary: str = "wing") -> Recipe:
    return Recipe(
        name=name,
        type="force_coefficient",
        params={
            "boundary": boundary,
            "direction": [1.0, 0.0, 0.0],
            "ref_area": 1.0,
            "ref_velocity": 1.0,
            "ref_density": 1.0,
        },
    )


def _make_case(tmp_path: Path, name: str = "case0001") -> Path:
    case_dir = tmp_path / name
    case_dir.mkdir(parents=True)
    return case_dir


_USER_DEFINITION = (
    '#include "cs_headers.h"\n'
    "\n"
    "void cs_user_extra_operations(cs_domain_t *domain)\n"
    "{\n"
    "  /* hand-written by an engineer */\n"
    "}\n"
)

_USER_DEFINITION_WITH_DISPATCH = (
    '#include "cs_headers.h"\n'
    '#include "cs_user_csauto_qoi.h"\n'
    "\n"
    "void cs_user_extra_operations(cs_domain_t *domain)\n"
    "{\n"
    "  /* hand-written */\n"
    "  csauto_qoi_dispatch(domain);\n"
    "}\n"
)


# --- managed mode -----------------------------------------------------------


def test_managed_writes_extra_operations_file(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    report = inject_user_files_into_case(case_dir, [_force_recipe()])
    assert isinstance(report, InjectionReport)
    assert report.mode == "managed"
    assert len(report.files_written) == 1
    target = report.files_written[0]
    assert target == case_dir / "SRC" / "cs_user_extra_operations.cpp"
    content = target.read_text(encoding="utf-8")
    assert "auto-generated by csauto" in content
    assert "csauto_qoi_force_wing" in content


def test_managed_creates_SRC_directory(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    assert not (case_dir / "SRC").exists()
    inject_user_files_into_case(case_dir, [_force_recipe()])
    assert (case_dir / "SRC").is_dir()


def test_managed_empty_recipes_is_noop(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    report = inject_user_files_into_case(case_dir, [])
    assert report.files_written == []
    assert not (case_dir / "SRC" / "cs_user_extra_operations.cpp").exists()


def test_managed_refuses_existing_user_authored_file(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    src = case_dir / "SRC"
    src.mkdir()
    pre_existing = src / "cs_user_extra_operations.cpp"
    pre_existing.write_text(_USER_DEFINITION, encoding="utf-8")

    with pytest.raises(QoIError, match=r"already defined in cs_user_extra_operations\.cpp"):
        inject_user_files_into_case(case_dir, [_force_recipe()])
    assert "hand-written by an engineer" in pre_existing.read_text(encoding="utf-8")


@pytest.mark.parametrize("extension", [".c", ".cc", ".cxx"])
def test_managed_refuses_user_file_with_alternate_extension(tmp_path: Path, extension: str) -> None:
    case_dir = _make_case(tmp_path)
    src = case_dir / "SRC"
    src.mkdir()
    (src / f"cs_user_extra_operations{extension}").write_text(_USER_DEFINITION, encoding="utf-8")
    with pytest.raises(QoIError, match="already defined in"):
        inject_user_files_into_case(case_dir, [_force_recipe()])


def test_managed_refuses_when_function_defined_in_another_file(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    src = case_dir / "SRC"
    src.mkdir()
    (src / "cs_user_source_terms.cpp").write_text(
        '#include "cs_headers.h"\n\nvoid cs_user_extra_operations(cs_domain_t *domain) {}\n',
        encoding="utf-8",
    )
    with pytest.raises(QoIError, match=r"already defined in cs_user_source_terms\.cpp"):
        inject_user_files_into_case(case_dir, [_force_recipe()])
    assert not (src / "cs_user_extra_operations.cpp").exists()


def test_managed_ignores_function_call_in_other_file(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
