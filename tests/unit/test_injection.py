def test_managed_overwrites_previously_csauto_managed_file(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    inject_user_files_into_case(case_dir, [_force_recipe(boundary="wing")])
    inject_user_files_into_case(case_dir, [_force_recipe(boundary="fuselage")])
    content = (case_dir / "SRC" / "cs_user_extra_operations.cpp").read_text(encoding="utf-8")
    assert "csauto_qoi_force_fuselage" in content
    assert "csauto_qoi_force_wing" not in content


# --- injected mode ----------------------------------------------------------


def test_injected_writes_csauto_qoi_pair(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    report = inject_user_files_into_case(case_dir, [_force_recipe()], mode="injected")
    names = sorted(p.name for p in report.files_written)
    assert names == ["cs_user_csauto_qoi.cpp", "cs_user_csauto_qoi.h"]
    src_dir = case_dir / "SRC"
    cpp = (src_dir / "cs_user_csauto_qoi.cpp").read_text(encoding="utf-8")
    h = (src_dir / "cs_user_csauto_qoi.h").read_text(encoding="utf-8")
    assert "csauto_qoi_dispatch(cs_domain_t *domain)" in cpp
    assert "void csauto_qoi_dispatch(cs_domain_t *domain);" in h
    assert "cs_user_extra_operations" not in cpp


def test_injected_does_not_touch_existing_user_file(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    src = case_dir / "SRC"
    src.mkdir()
    user_file = src / "cs_user_source_terms.cpp"
    user_file.write_text(
        '#include "cs_headers.h"\n\nvoid cs_user_extra_operations(cs_domain_t *domain){}\n',
        encoding="utf-8",
    )
    original = user_file.read_text(encoding="utf-8")
    report = inject_user_files_into_case(case_dir, [_force_recipe()], mode="injected")
    assert report.user_file_with_extra_ops == user_file
    assert user_file.read_text(encoding="utf-8") == original  # untouched
    assert report.dispatch_call_present is False
    assert report.needs_user_action is True


def test_injected_detects_dispatch_already_wired(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    src = case_dir / "SRC"
    src.mkdir()
    (src / "cs_user_extra_operations.cpp").write_text(_USER_DEFINITION_WITH_DISPATCH, encoding="utf-8")
    report = inject_user_files_into_case(case_dir, [_force_recipe()], mode="injected")
    assert report.dispatch_call_present is True
    assert report.needs_user_action is False


def test_injected_is_idempotent(tmp_path: Path) -> None:
    case_dir = _make_case(tmp_path)
    r1 = inject_user_files_into_case(case_dir, [_force_recipe()], mode="injected")
    snapshots = {p: p.read_text(encoding="utf-8") for p in r1.files_written}
    r2 = inject_user_files_into_case(case_dir, [_force_recipe()], mode="injected")
    assert {p.name for p in r2.files_written} == {p.name for p in r1.files_written}
    for p in r2.files_written:
        assert p.read_text(encoding="utf-8") == snapshots[p]


