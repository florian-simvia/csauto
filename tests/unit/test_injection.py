# --- inject_user_files_into_runs --------------------------------------------


def test_inject_into_runs_managed_returns_one_report_per_case(tmp_path: Path) -> None:
    runs = tmp_path / "RUNS"
    runs.mkdir()
    for name in ("case0001", "case0002", "case0003"):
        (runs / name).mkdir()
    (runs / "MESH").mkdir()  # non-case dir, must be ignored

    reports = inject_user_files_into_runs(runs, [_force_recipe()])
    assert {r.case_dir.name for r in reports} == {"case0001", "case0002", "case0003"}
    assert all(r.mode == "managed" for r in reports)
    assert all(r.files_written for r in reports)


def test_inject_into_runs_injected_writes_pair_per_case(tmp_path: Path) -> None:
    runs = tmp_path / "RUNS"
    runs.mkdir()
    for name in ("case0001", "case0002"):
        (runs / name).mkdir()
    reports = inject_user_files_into_runs(runs, [_force_recipe()], mode="injected")
    assert all(len(r.files_written) == 2 for r in reports)
    assert all(r.mode == "injected" for r in reports)


def test_inject_into_runs_no_recipes_is_noop(tmp_path: Path) -> None:
    runs = tmp_path / "RUNS"
    runs.mkdir()
    (runs / "case0001").mkdir()
    assert inject_user_files_into_runs(runs, []) == []


def test_inject_into_runs_raises_when_runs_dir_missing(tmp_path: Path) -> None:
    with pytest.raises(QoIError, match="runs_dir not found"):
        inject_user_files_into_runs(tmp_path / "ghost", [_force_recipe()])


def test_inject_into_runs_managed_stops_on_first_conflict(tmp_path: Path) -> None:
    runs = tmp_path / "RUNS"
    runs.mkdir()
    (runs / "case0001").mkdir()
    case2 = runs / "case0002"
    case2.mkdir()
    (case2 / "SRC").mkdir()
    (case2 / "SRC" / "cs_user_extra_operations.cpp").write_text(_USER_DEFINITION, encoding="utf-8")
    (runs / "case0003").mkdir()

    with pytest.raises(QoIError, match="already defined in"):
        inject_user_files_into_runs(runs, [_force_recipe()])
    # case0001 was processed before the conflict; case0003 must not have been touched.
    assert (runs / "case0001" / "SRC" / "cs_user_extra_operations.cpp").is_file()
    assert not (runs / "case0003" / "SRC").exists()
